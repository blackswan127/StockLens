function mockTimeSeries(annual: any[], quarterly: any[]) {
  vi.mocked(yahooService.getFundamentalsTimeSeries).mockImplementation(
    async (_symbol, _from, _to, type) => (type === 'quarterly' ? quarterly : annual)
  );
}

function mockHappyPath(overrides: {
  annual?: any[];
  quarterly?: any[];
  basicFinancials?: any;
  edgar?: any;
  fred?: any;
  peers?: any[];
  profile?: any;
  quote?: any;
} = {}) {
  vi.mocked(yahooService.getProfile).mockResolvedValue(
    overrides.profile ?? { name: 'Acme Corp', country: 'US' }
  );
  vi.mocked(yahooService.getQuote).mockResolvedValue(
    overrides.quote ?? {
      price: 50,
      high_52w: 60,
      low_52w: 30,
      epsTrailingTwelveMonths: 5
    }
  );
  vi.mocked(yahooService.getBasicFinancials).mockResolvedValue(
    overrides.basicFinancials ?? BASIC_FINANCIALS
  );
  mockTimeSeries(
    overrides.annual ?? ANNUAL_STATEMENTS,
    overrides.quarterly ?? QUARTERLY_TTM
  );
  vi.mocked(yahooService.getGrowthEstimates).mockResolvedValue({ growthEstimate5yr: 0.1 });
  vi.mocked(fredService.getSeries).mockResolvedValue(
    overrides.fred ?? {
      observations: [
        { date: '2026-01-01', value: '3.80' },
        { date: '2026-02-01', value: '4.20' }
      ]
    }
  );
  vi.mocked(edgarService.getFinancials).mockResolvedValue(
    overrides.edgar === undefined ? EDGAR_MATCH : overrides.edgar
  );
  vi.mocked(fetchPeersForReport).mockResolvedValue(
    overrides.peers ?? [
      { pe: '10.00x' },
      { pe: '20.00x' },
      { pe: '30.00x' },
      { pe: '40.00x' }
    ]
  );
}

describe('dcfService.getDCFData', () => {
  beforeEach(() => {
    vi.resetAllMocks();
    mockHappyPath();
  });

  describe('WACC inputs (CAPM + cost of debt)', () => {
    it('derives risk-free rate, beta, tax shield and synthetic cost of debt from a hand-checkable fixture', async () => {
      const data = await dcfService.getDCFData('ACME');

      // CAPM inputs
      expect(data.riskFreeRate).toBeCloseTo(0.042, 6);
      expect(data.beta).toBe(1.2);
      expect(data.riskFreeRate! + data.beta! * 0.05).toBeCloseTo(0.102, 6);

      // Synthetic credit rating from ICR = EBIT / interest = 250M / 10M = 25 => AAA
      expect(data.syntheticRating).toBe('AAA');
      expect(data.syntheticCostOfDebt).toBeCloseTo(0.042 + 0.0069, 6);

      // Tax shield on debt and equity/debt weights an aggregator would use for WACC
      const afterTaxCostOfDebt = data.syntheticCostOfDebt! * (1 - data.taxRate!);
      const equityWeight = data.marketCap! / (data.marketCap! + data.totalDebt!);
      expect(afterTaxCostOfDebt).toBeCloseTo(0.036675, 6);
      expect(equityWeight).toBeCloseTo(5_000 * M / (5_000 * M + 500 * M), 6);

      expect(data.provenance.riskFreeRate).toMatchObject({
        source: 'FRED DGS10',
        fallbackApplied: false
      });
      expect(data.provenance.beta.source).toBe('Yahoo Basic Financials');
    });

    it('applies the synthetic rating boundaries strictly (ICR exactly 2.5 => BB+, not BBB)', async () => {
      const singleYear = [
        {
          date: '2024-12-31T00:00:00.000Z',
          totalRevenue: 1_000 * M,
          freeCashFlow: 100 * M,
          interestExpense: 10 * M,
          taxRateForCalcs: 0.25,
          operatingIncome: 25 * M
        }
      ];

      mockHappyPath({ annual: singleYear, quarterly: [], edgar: null });

      const data = await dcfService.getDCFData('BOUNDARY');

      // ICR = 25M / 10M = 2.5; the table uses strict `>` so 2.5 lands in BB+ (spread 0.0231)
      expect(data.syntheticRating).toBe('BB+');
      expect(data.syntheticCostOfDebt).toBeCloseTo(0.042 + 0.0231, 6);
      // No interest-free treatment: after-tax interest is still added back (10M * 0.75)
      expect(data.historicalFCFF[0].value).toBe(107_500_000);
    });

    it('treats zero interest expense as an AAA credit profile', async () => {
      const singleYear = [
        {
          date: '2024-12-31T00:00:00.000Z',
          totalRevenue: 1_000 * M,
          freeCashFlow: 100 * M,
          taxRateForCalcs: 0.25,
          operatingIncome: 100 * M
        }
      ];

      mockHappyPath({ annual: singleYear, quarterly: [], edgar: null });

      const data = await dcfService.getDCFData('NOINTEREST');

      expect(data.interestExpense).toBeNull();
      expect(data.syntheticRating).toBe('AAA');
      expect(data.syntheticCostOfDebt).toBeCloseTo(0.0489, 6);
      // No interest => no add-back
      expect(data.historicalFCFF[0].value).toBe(100 * M);
    });

    it('uses the 21% statutory tax rate when taxRateForCalcs is missing or out of range', async () => {
      const singleYear = [
        {
          date: '2024-12-31T00:00:00.000Z',
          totalRevenue: 1_000 * M,
          freeCashFlow: 100 * M,
          interestExpense: 10 * M,
          operatingIncome: 100 * M
        }
      ];

      mockHappyPath({ annual: singleYear, quarterly: [], edgar: null });

      const data = await dcfService.getDCFData('NOTAX');

      expect(data.taxRate).toBeNull();
      // 10M * (1 - 0.21) = 7.9M add-back
      expect(data.historicalFCFF[0].value).toBe(107_900_000);

      const outOfRange = [{ ...singleYear[0], taxRateForCalcs: 1.4 }];
      mockHappyPath({ annual: outOfRange, quarterly: [], edgar: null });

      const second = await dcfService.getDCFData('BADTAX');
      expect(second.taxRate).toBe(1.4);
      expect(second.historicalFCFF[0].value).toBe(107_900_000);
    });

    it('falls back to a 4.25% risk-free rate when FRED throws (US path)', async () => {
      const warnSpy = vi.spyOn(console, 'warn').mockImplementation(() => {});
      vi.mocked(fredService.getSeries).mockRejectedValue(new Error('FRED down'));

      try {
        const data = await dcfService.getDCFData('FREDFAIL');

        expect(data.riskFreeRate).toBe(0.0425);
        expect(data.provenance.riskFreeRate).toMatchObject({
          source: 'US 10y Treasury Hardcoded Fallback',
          fallbackApplied: true
        });
        expect(data.syntheticCostOfDebt).toBeCloseTo(0.0425 + 0.0069, 6);
      } finally {
        warnSpy.mockRestore();
      }
    });

    it('upgrades the 4.25% US default to the live FRED DGS10 observation', async () => {
      vi.mocked(fredService.getSeries).mockResolvedValue({
        observations: [
          { date: '2026-01-01', value: '3.80' },
          { date: '2026-02-01', value: '4.20' }
        ]
      });

      const data = await dcfService.getDCFData('LIVERF');

      expect(data.riskFreeRate).toBeCloseTo(0.042, 6);
      expect(data.provenance.riskFreeRate).toMatchObject({
        source: 'FRED DGS10',
        fallbackApplied: false,
        timestamp: '2026-02-01'
      });
    });

    it('applies the 4.25% US fallback when FRED returns empty observations instead of throwing', async () => {
      vi.mocked(fredService.getSeries).mockResolvedValue({ available: false, observations: [] });

      const data = await dcfService.getDCFData('EMPTYFRED');

      // Unavailable/empty FRED data is an honest "no live rate" signal; the
      // documented hardcoded US 10y Treasury default keeps the model usable.
      expect(data.riskFreeRate).toBe(0.0425);
      expect(data.provenance.riskFreeRate).toMatchObject({
        source: 'US 10y Treasury Hardcoded Fallback',
        fallbackApplied: true
      });
      expect(data.syntheticRating).toBe('AAA');
      expect(data.syntheticCostOfDebt).toBeCloseTo(0.0425 + 0.0069, 6);
    });

    it('uses the India 10y series (and INR currency) for Indian listings', async () => {
      mockHappyPath({
        profile: { name: 'Reliance Industries', country: 'India' },
        fred: { observations: [{ date: '2026-02-01', value: '7.10' }] }
      });

      const data = await dcfService.getDCFData('RELIANCE.NS');

      expect(fredService.getSeries).toHaveBeenCalledWith('INDIRLTLT01STM');
      expect(data.riskFreeRate).toBeCloseTo(0.071, 6);
      expect(data.currency).toBe('INR');
      expect(data.syntheticCostOfDebt).toBeCloseTo(0.071 + 0.0069, 6);
    });

    it('keeps the hardcoded 7.1% India fallback when FRED returns no observations', async () => {
      mockHappyPath({
        profile: { name: 'Reliance Industries', country: 'IN' },
        fred: { observations: [] }
      });

      const data = await dcfService.getDCFData('RELIANCE.BO');

      expect(data.riskFreeRate).toBe(0.071);
      expect(data.currency).toBe('INR');
    });
  });

  describe('two-stage projection inputs (growth, margins, TTM, terminal inputs)', () => {
    it('builds annual + TTM revenue/FCF series with the unlevered FCFF add-back', async () => {
      const data = await dcfService.getDCFData('ACME');

      expect(data.historicalFCF.map((row: any) => row.year)).toEqual([2021, 2022, 2023, 2024, 2025]);
      expect(data.historicalFCF.map((row: any) => row.value)).toEqual([
        100 * M,
        110 * M,
        121 * M,
        133_100_000,
        200 * M
      ]);
      expect(data.historicalFCF[4].source).toBe('Yahoo Quarterly TTM');

      expect(data.historicalRevenue.map((row: any) => row.value)).toEqual([
        1_000 * M,
        1_100 * M,
        1_210 * M,
        1_331 * M,
        1_600 * M
      ]);

      expect(data.historicalFCFF.map((row: any) => row.value)).toEqual([
        107_500_000,
        117_500_000,
        128_500_000,
        140_600_000,
        207_900_000
      ]);

      // Growth trajectory a two-stage model reads from the payload
      const revenue2021 = data.historicalRevenue[0].value;
      const revenue2024 = data.historicalRevenue[3].value;
      const cagr = Math.pow(revenue2024 / revenue2021, 1 / 3) - 1;
      expect(cagr).toBeCloseTo(0.1, 6); // exactly 10% historical CAGR
      expect(data.analystGrowthEstimate5yr).toBe(0.1);
    });

    it('ignores a partial quarterly set (fewer than 4 quarters) instead of blending a fake TTM', async () => {
      mockHappyPath({ quarterly: QUARTERLY_TTM.slice(0, 3) });

      const data = await dcfService.getDCFData('PARTIALQ');

      expect(data.historicalFCF).toHaveLength(4);
      expect(data.historicalFCF.some((row: any) => row.source === 'Yahoo Quarterly TTM')).toBe(false);
      expect(data.historicalRevenue).toHaveLength(4);
    });

    it('computes the peer median P/E (even cohort averages the middle pair)', async () => {
      const data = await dcfService.getDCFData('ACME');

      expect(data.peerMedianPE).toBe(25);
    });

    it('falls back to shares × price for market cap when basic financials omit it', async () => {
      mockHappyPath({
        basicFinancials: {
          metric: {
            sharesOutstanding: 100 * M,
            totalDebt: 500 * M,
            totalCash: 100 * M,
            beta: 1.2
          }
        }
      });

      const data = await dcfService.getDCFData('MCFALLBACK');

      expect(data.marketCap).toBe(5_000 * M);
      expect(data.provenance.marketCap).toMatchObject({
        source: 'Shares * Price (Fallback)',
        fallbackApplied: true
      });
    });
  });

  describe('guardrails and edge cases', () => {
    it('throws a 404-tagged error when the real-time quote is unavailable', async () => {
      vi.mocked(yahooService.getQuote).mockRejectedValue(new Error('Symbol not found'));

      await expect(dcfService.getDCFData('NOPE')).rejects.toMatchObject({
        message: 'Could not fetch real-time quote for symbol NOPE',
        status: 404
      });
    });

    it('returns null shares (and no market cap) instead of fabricating a denominator', async () => {
      mockHappyPath({
        basicFinancials: { metric: {} },
        annual: ANNUAL_STATEMENTS.map((row) => {
          const { ordinarySharesNumber: _shares, ...rest } = row;
          return rest;
        })
      });

      const data = await dcfService.getDCFData('NOSHARES');

      expect(data.sharesOutstanding).toBeNull();
      expect(data.marketCap).toBeUndefined();
      expect(data.provenance.sharesOutstanding).toBeUndefined();
    });

    it('passes negative FCF through without throwing (sign is preserved in FCFF)', async () => {
      const negativeFcf = [
        {
          date: '2024-12-31T00:00:00.000Z',
          totalRevenue: 1_000 * M,
          freeCashFlow: -50 * M,
          interestExpense: 10 * M,
          taxRateForCalcs: 0.25,
          operatingIncome: 10 * M
        }
      ];

      mockHappyPath({ annual: negativeFcf, quarterly: [], edgar: null });

      const data = await dcfService.getDCFData('NEGFCF');

      expect(data.historicalFCF[0].value).toBe(-50 * M);
      expect(data.historicalFCFF[0].value).toBe(-42_500_000);
      expect(data.dataConfidence).toBe('low');
    });

    it('does not divide by zero or throw for zero revenue', async () => {
      const zeroRevenue = [
        {
          date: '2024-12-31T00:00:00.000Z',
          totalRevenue: 0,
          freeCashFlow: 100 * M,
          interestExpense: 10 * M,
          taxRateForCalcs: 0.25,
          operatingIncome: 50 * M
        }
      ];

      mockHappyPath({
        annual: zeroRevenue,
        quarterly: [],
        edgar: {
          incomeStatement: [{ label: 'Revenue', values: { '2024': 500 } }],
          cashFlow: [
            { label: 'Cash generated by operating activities', values: { '2024': 150 } },
            { label: 'Payments for property, plant and equipment', values: { '2024': 50 } }
          ],
          balanceSheet: []
        }
      });

      const data = await dcfService.getDCFData('ZEROREV');

      expect(data.historicalRevenue[0].value).toBe(0);
      // Division guard `(yahooRevMils || 1)` prevents NaN; mismatch keeps confidence at medium.
      expect(data.dataConfidence).toBe('medium');
    });

    it('passes negative revenue through and degrades EDGAR confidence instead of throwing', async () => {
      const negativeRevenue = [
        {
          date: '2024-12-31T00:00:00.000Z',
          totalRevenue: -500 * M,
          freeCashFlow: 100 * M,
          interestExpense: 10 * M,
          taxRateForCalcs: 0.25,
          operatingIncome: 50 * M
        }
      ];

      mockHappyPath({
        annual: negativeRevenue,
        quarterly: [],
        edgar: {
          incomeStatement: [{ label: 'Revenue', values: { '2024': 500 } }],
          cashFlow: [
            { label: 'Cash generated by operating activities', values: { '2024': 150 } },
            { label: 'Payments for property, plant and equipment', values: { '2024': 50 } }
          ],
          balanceSheet: []
        }
      });

      const data = await dcfService.getDCFData('NEGREV');

      expect(data.historicalRevenue[0].value).toBe(-500 * M);
      expect(data.dataConfidence).toBe('medium');
    });

    it('exposes WACC ingredients without enforcing a WACC > terminal-growth guard at the data layer', async () => {
      // The WACC <= g guard lives in src/utils/dcfCalculator.ts (client), not here.
      mockHappyPath({
        fred: { observations: [{ date: '2026-02-01', value: '0.50' }] }
      });

      const data = await dcfService.getDCFData('LOWRF');

      expect(data.riskFreeRate).toBeCloseTo(0.005, 6);
      expect(data.beta).toBe(1.2);
      // No throw: ingredients are returned for the client calculator to validate.
      expect(data.syntheticRating).toBe('AAA');
    });
  });

  describe('data confidence classification', () => {
    it('classifies as high when SEC and Yahoo annual FCF/revenue agree within 5%', async () => {
      const data = await dcfService.getDCFData('HIGHCONF');

      expect(data.dataConfidence).toBe('high');
    });

    it('classifies as medium when SEC is available but disagrees with Yahoo', async () => {
      mockHappyPath({
        edgar: {
          incomeStatement: [{ label: 'Revenue', values: { '2024': 2_000 } }],
          cashFlow: [
            { label: 'Cash generated by operating activities', values: { '2024': 400 } },
            { label: 'Payments for property, plant and equipment', values: { '2024': 50 } }
          ],
          balanceSheet: []
        }
      });

      const data = await dcfService.getDCFData('MEDCONF');

      expect(data.dataConfidence).toBe('medium');
    });

    it('classifies as low when EDGAR is unavailable', async () => {
      vi.mocked(edgarService.getFinancials).mockRejectedValue(new Error('EDGAR down'));

      const data = await dcfService.getDCFData('LOWCONF');

      expect(data.dataConfidence).toBe('low');
    });

    it('classifies as medium when EDGAR is present but the required rows are missing', async () => {
      mockHappyPath({
        edgar: { incomeStatement: [], cashFlow: [], balanceSheet: [] }
      });

      const data = await dcfService.getDCFData('NOLABELS');

      expect(data.dataConfidence).toBe('medium');
    });

    it('compares the annual period (not TTM) against the annual SEC filing', async () => {
      // The TTM series (1,600M revenue / 200M FCF) deliberately diverges from SEC.
      // Confidence must still be high because the 2024 annual figures match.
      const data = await dcfService.getDCFData('TTMCONF');

      expect(data.historicalRevenue[4].value).toBe(1_600 * M);
      expect(data.historicalFCF[4].value).toBe(200 * M);
      expect(data.dataConfidence).toBe('high');
    });
  });
});
