const M = 1_000_000;

/**
 * Deterministic fixture (all values in whole dollars):
 *
 * Annual (oldest -> newest)
 *   year  revenue    FCF      interest  tax   EBIT
 *   2021  1,000M     100M     10M       25%   200M
 *   2022  1,100M     110M     10M       25%   220M
 *   2023  1,210M     121M     10M       25%   235M
 *   2024  1,331M     133.1M   10M       25%   250M
 *
 * Quarterly TTM (4 quarters): revenue 400M each, FCF 50M each, interest 2.5M each
 *   Quarterly rows omit taxRateForCalcs, so the 21% statutory fallback applies:
 *   TTM after-tax interest = 4 * 2.5M * 0.79 = 7.9M
 *   => TTM revenue 1,600M, TTM FCF 200M, TTM unlevered FCFF 207.9M
 *
 * Unlevered FCFF (FCF + after-tax interest):
 *   2021 107.5M, 2022 117.5M, 2023 128.5M, 2024 140.6M, TTM 207.9M
 *
 * Capital structure / market data:
 *   shares 100M, price 50 => market cap 5,000M; total debt 500M; cash 100M; beta 1.2
 *   risk-free (DGS10) 4.2% ; EBIT 250M / interest 10M => ICR 25 => AAA (spread 0.69%)
 *   pre-tax cost of debt = 4.2% + 0.69% = 4.89%
 *   after-tax cost of debt = 4.89% * (1 - 0.25) = 3.6675%
 *   CAPM cost of equity (at a 5% ERP) = 4.2% + 1.2 * 5% = 10.2%
 */
